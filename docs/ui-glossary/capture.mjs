#!/usr/bin/env node
// Regenerates the reference screenshots in ./screenshots.
//
// Only public, side-effect-free GET routes are captured. Auth-gated routes
// (/dashboard, /admin, the Section editor, checkout) are deliberately absent:
// this project points at a hosted Supabase, and capturing them would mean
// creating real accounts and real rows. Those plates are wireframe-only.
//
//   npm run dev                       # in another shell, on port 3000
//   node docs/ui-glossary/capture.mjs
//
// Uses whatever Chromium is already on the machine (CHROME_PATH), falling back
// to Playwright's own download. No new project dependency: playwright is
// already in devDependencies.

import { chromium } from "playwright"
import { execSync } from "node:child_process"
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, "screenshots")
const BASE = process.env.GLOSSARY_BASE_URL ?? "http://localhost:3000"

/** Each entry mirrors one plate id in data/terms.js. */
const SHOTS = [
  { plate: "site-shell", path: "/", widths: ["desktop", "mobile"], fullPage: false },
  { plate: "templates-gallery", path: "/templates", widths: ["desktop", "mobile"], fullPage: false },
  { plate: "template-detail", path: "/templates/malay-wedding", widths: ["desktop", "mobile"], fullPage: false },
  { plate: "card-preview", path: "/templates/preview/malay-wedding", widths: ["mobile"], fullPage: false },
  { plate: "invitation-card", path: "/templates/preview/malay-wedding-v2", widths: ["desktop", "mobile"], fullPage: false },
]

const VIEWPORTS = {
  desktop: { width: 1280, height: 860 },
  mobile: { width: 390, height: 780 },
}

// Hide the Next.js dev-tools badge so it never reads as product UI.
const HIDE_DEV_CHROME = `
  nextjs-portal, #__next-build-watcher, [data-nextjs-toast] { display: none !important; }
`

async function main() {
  mkdirSync(OUT, { recursive: true })

  const browser = await chromium.launch({
    executablePath: process.env.CHROME_PATH || undefined,
  })

  const captured = []
  for (const shot of SHOTS) {
    for (const width of shot.widths) {
      const page = await browser.newPage({
        viewport: VIEWPORTS[width],
        deviceScaleFactor: 2,
        reducedMotion: "reduce",
      })
      const url = BASE + shot.path
      await page.goto(url, { waitUntil: "networkidle", timeout: 60_000 })
      await page.addStyleTag({ content: HIDE_DEV_CHROME })
      await page.waitForTimeout(600)

      const file = `${shot.plate}-${width}.jpg`
      await page.screenshot({
        path: join(OUT, file),
        type: "jpeg",
        quality: 78,
        fullPage: shot.fullPage,
      })
      await page.close()

      captured.push({ plate: shot.plate, width, file, route: shot.path })
      console.log(`captured ${file}  ←  ${url}`)
    }
  }

  await browser.close()

  let commit = "unknown"
  try {
    commit = execSync("git rev-parse --short HEAD", { cwd: HERE }).toString().trim()
  } catch {}

  // The artifact reads this to label each screenshot with real provenance.
  // Written twice: .json for humans and tooling, .js for the artifact, which
  // must work from file:// where fetch() of a local .json is blocked.
  const manifest = {
    capturedAt: new Date().toISOString(),
    commit,
    baseUrl: BASE,
    viewports: VIEWPORTS,
    shots: captured,
  }
  writeFileSync(join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n")
  writeFileSync(
    join(OUT, "manifest.js"),
    "/* Generated by docs/ui-glossary/capture.mjs — do not edit by hand. */\n" +
      "window.KAMY_GLOSSARY_SHOTS = " + JSON.stringify(manifest, null, 2) + "\n",
  )
  console.log(`\nwrote ${captured.length} screenshots + manifest.json (commit ${commit})`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
